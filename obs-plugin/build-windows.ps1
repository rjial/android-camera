# Builds the ACAM Camera OBS source for Windows (acam-source.dll) with MSVC, without CMake or an
# OBS SDK: OBS doesn't ship one for Windows, so this fetches the libobs headers for the *installed*
# OBS version from GitHub and makes an import library from the installed obs.dll.
#
#   obs-plugin\build-windows.ps1            build into obs-plugin\build-win\
#   obs-plugin\build-windows.ps1 -Install   also install for OBS (no admin needed):
#                                           %ProgramData%\obs-studio\plugins\acam-source\
#
# Needs Visual Studio 2022 (or Build Tools) with the C++ workload, git, and OBS Studio installed.
param(
    [switch]$Install,
    [string]$ObsDir = "C:\Program Files\obs-studio"
)
$ErrorActionPreference = "Stop"

$here = $PSScriptRoot
$deps = Join-Path $here ".deps"
$out = Join-Path $here "build-win"
New-Item -ItemType Directory -Force -Path $deps, $out | Out-Null

$obsDll = Join-Path $ObsDir "bin\64bit\obs.dll"
if (-not (Test-Path $obsDll)) { throw "OBS not found at $ObsDir (pass -ObsDir)" }
$obsVersion = (Get-Item (Join-Path $ObsDir "bin\64bit\obs64.exe")).VersionInfo.ProductVersion
$acamVersion = (Get-Content (Join-Path $here "..\VERSION") -Raw).Trim()
Write-Host "OBS $obsVersion, ACAM $acamVersion"

# libobs headers for exactly this OBS version (the plugin ABI follows it).
$src = Join-Path $deps "obs-src-$obsVersion"
if (-not (Test-Path (Join-Path $src "libobs\obs-module.h"))) {
    if (Test-Path $src) { Remove-Item -Recurse -Force $src }
    # Through cmd: Windows PowerShell turns git's progress on stderr into errors.
    cmd /c "git -c advice.detachedHead=false clone -q --depth 1 --branch $obsVersion --filter=blob:none --sparse https://github.com/obsproject/obs-studio.git `"$src`" 2>&1"
    if ($LASTEXITCODE -ne 0) { throw "git clone of obs-studio $obsVersion failed" }
    cmd /c "git -C `"$src`" sparse-checkout set libobs 2>&1"
    if ($LASTEXITCODE -ne 0) { throw "git sparse-checkout failed" }
}

# obsconfig.h is generated by OBS's own CMake build; the plugin only needs it to exist.
$inc = Join-Path $deps "include"
New-Item -ItemType Directory -Force -Path $inc | Out-Null
@"
#pragma once
#define OBS_DATA_PATH "../../data"
#define OBS_PLUGIN_PATH "../../obs-plugins/64bit"
#define OBS_PLUGIN_DESTINATION "obs-plugins/64bit"
#define OBS_INSTALL_PREFIX ""
#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
"@ | Set-Content -Encoding ascii (Join-Path $inc "obsconfig.h")

# MSVC environment.
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw "Visual Studio with the C++ tools not found" }
$vcvars = Join-Path $vs "VC\Auxiliary\Build\vcvars64.bat"

# Import library for obs.dll, from its export table.
$def = Join-Path $out "obs.def"
$lib = Join-Path $out "obs.lib"
$dll = Join-Path $out "acam-source.dll"
$exports = cmd /c "`"$vcvars`" >nul 2>&1 && dumpbin /nologo /exports `"$obsDll`" 2>&1"
$names = $exports | ForEach-Object { if ($_ -match '^\s+\d+\s+[0-9A-F]+\s+[0-9A-F]+\s+(\S+)') { $Matches[1] } }
if ($names.Count -lt 100) { throw "could not read the exports of $obsDll" }
(@("LIBRARY obs", "EXPORTS") + $names) | Set-Content -Encoding ascii $def

$cl = @(
    "`"$vcvars`" >nul 2>&1",
    "lib /nologo /def:`"$def`" /machine:x64 /out:`"$lib`" >nul",
    ("cl /nologo /O2 /W3 /MD /LD /utf-8 /DACAM_VERSION=\`"$acamVersion\`" " +
     "/I`"$src\libobs`" /I`"$inc`" /Fo`"$out\\`" `"$here\src\acam-source.c`" " +
     "/link /OUT:`"$dll`" /IMPLIB:`"$out\acam-source.lib`" `"$lib`"")
) -join " && "
cmd /c "$cl 2>&1"
if ($LASTEXITCODE -ne 0) { throw "build failed" }
Write-Host "Built $dll"

if ($Install) {
    # OBS 28+ loads plugins from here in addition to its own folder; a normal user may write it.
    $dest = Join-Path $env:ProgramData "obs-studio\plugins\acam-source"
    New-Item -ItemType Directory -Force -Path (Join-Path $dest "bin\64bit") | Out-Null
    Copy-Item -Force $dll (Join-Path $dest "bin\64bit\acam-source.dll")
    Copy-Item -Recurse -Force (Join-Path $here "data") $dest
    Write-Host "Installed to $dest (restart OBS)"
}
